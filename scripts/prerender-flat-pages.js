#!/usr/bin/env node
/* Family&Flats: write each verified flat's details into its page HTML, so Google and
   no-JavaScript visitors see the same content ff-flat-page.js shows.
   Run from public_html after listings.js changes:  node scripts/prerender-flat-pages.js [--check]
   It runs ff-flat-page.js itself, so the HTML always matches what the browser renders. */
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm");
const ROOT = path.resolve(__dirname, "..");
const SITE = "https://familyandflats.com";
const START = "<!-- FF-PRERENDER START (generated by scripts/prerender-flat-pages.js; do not edit by hand) -->";
const END = "<!-- FF-PRERENDER END -->";
const check = process.argv.includes("--check");

function load(rel) { const ctx = { window: {} }; vm.runInNewContext(fs.readFileSync(path.join(ROOT, rel), "utf8"), ctx); return ctx.window; }
const all = (load("assets/data/listings.js").FF_LISTINGS || []).concat(load("assets/data/verified-listings.js").FF_VERIFIED_LISTINGS || []);
const pageJs = fs.readFileSync(path.join(ROOT, "assets/js/ff-flat-page.js"), "utf8");

function render(flatId) {
  // Minimal stand-in DOM: captures root.innerHTML, ignores the interactive wiring.
  const stub = () => new Proxy(function () {}, { get: (t, k) => (k === "classList" ? { add() {}, remove() {}, toggle() {}, contains() { return false; } } : k === "style" ? {} : k === "dataset" ? {} : stub()), set: () => true, apply: () => stub() });
  const root = { innerHTML: "", addEventListener() {}, querySelectorAll: () => [], querySelector: () => null };
  const doc = { title: "", getElementById: (id) => (id === "ffp-root" ? root : stub()), body: { getAttribute: () => flatId }, addEventListener() {}, activeElement: null };
  vm.runInNewContext(pageJs, { window: { FF_LISTINGS: all, FF_VERIFIED_LISTINGS: [] }, document: doc, encodeURIComponent, String, Math, Array, Number });
  return { html: root.innerHTML, title: doc.title };
}

let changed = 0, problems = 0;
for (const item of all) {
  if (!item || !item.detailUrl || !/verified/i.test(item.status || "")) continue;
  const file = path.join(ROOT, item.detailUrl.replace(/^\//, ""));
  if (!fs.existsSync(file)) continue;
  const raw = fs.readFileSync(file, "utf8"), nl = raw.includes("\r\n") ? "\r\n" : "\n";
  let src = raw.replace(/\r\n/g, "\n");
  if (!src.includes(`data-flat-id="${item.id}"`)) { console.log(`SKIP ${item.detailUrl}: data-flat-id does not match ${item.id}`); problems++; continue; }
  const { html } = render(item.id);
  if (!html) { console.log(`SKIP ${item.detailUrl}: nothing rendered`); problems++; continue; }
  const num = (s) => { const m = String(s || "").replace(/,/g, "").match(/(\d+(?:\.\d+)?)/); return m ? +m[1] : 0; };
  // Interactive parts (lightbox, sticky bar) only make sense once the script runs; drop them from the static copy.
  const first = (item.gallery && item.gallery[0]) || item.image || "";
  const cap0 = (item.captions && item.captions[0]) ? item.captions[0] + " – " : "";
  const n = (item.gallery || [item.image]).filter(Boolean).length;
  const imgAlt = `${cap0}${num(item.bhk)} BHK flat in ${item.project}, photo 1 of ${n}`.replace(/"/g, "&quot;");
  const staticHtml0 = html.replace('<img id="ffp-main" alt="">', `<img id="ffp-main" src="${first}" alt="${imgAlt}">`);
  const staticHtml1 = staticHtml0.replace('<span class="ffp-cap" id="ffp-cap"></span><span class="ffp-count" id="ffp-count"></span>',
    `<span class="ffp-cap" id="ffp-cap">${String((item.captions || [])[0] || "").replace(/</g, "&lt;")}</span><span class="ffp-count" id="ffp-count">1 / ${n}</span>`);
  const staticHtml = staticHtml1.replace(/<div class="ffp-lb"[\s\S]*$/, "").replace(/<div class="ffp-bar">[\s\S]*?<\/a><\/div>/, "");
  const block = `${START}\n${staticHtml}\n    ${END}`;
  const mainRe = /(<main class="ffp" id="ffp-root">)([\s\S]*?)(<\/main>)/;
  if (!mainRe.test(src)) { console.log(`SKIP ${item.detailUrl}: no <main id="ffp-root">`); problems++; continue; }
  let out = src.replace(mainRe, (m, a, b, c) => `${a}\n    ${block}\n  ${c}`);
  // Unique title: configuration + size + floor, so two 4 BHK pages never share one.
  const size = num(item.size), isLease = item.type === "Lease";
  const title = `${num(item.bhk)} BHK Flat ${isLease ? "for Rent" : "for Sale"} in ${item.project}` + (size ? `, ${size.toLocaleString("en-IN")} sq. ft.` : "") + (item.floor ? `, ${item.floor}` : "") + " | Family&Flats";
  const tEsc = title.replace(/&/g, "&amp;").replace(/&amp;Flats/g, "&Flats");
  out = out.replace(/<title>[\s\S]*?<\/title>/, `<title>${title}</title>`)
           .replace(/(<meta property="og:title" content=")[^"]*(")/, `$1${title.replace(/&/g, "&amp;")}$2`)
           .replace(/<link rel="canonical" href="\/([^"]*)">/, `<link rel="canonical" href="${SITE}/$1">`)
           .replace(/(<meta property="og:url" content=")\/([^"]*")/, `$1${SITE}/$2`)
           .replace(/ff-flat-page\.js\?v=\d+/, "ff-flat-page.js?v=5");
  out = out.replace(/\n/g, nl);
  if (out !== raw) { changed++; if (check) console.log(`OUT OF DATE ${item.detailUrl}`); else { fs.writeFileSync(file, out); console.log(`WROTE ${item.detailUrl}`); } }
}
if (check) { console.log(changed ? `PRERENDER_CHECK=FAIL ${changed}` : "PRERENDER_CHECK=PASS"); process.exit(changed || problems ? 1 : 0); }
console.log(`PRERENDER_DONE changed=${changed} problems=${problems}`);
